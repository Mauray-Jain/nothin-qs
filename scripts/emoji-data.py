#!/usr/bin/env python3
"""Regenerate shell/modules/launcher/EmojiData.js from the unicode-emoji-json
npm package (MIT): npm pack unicode-emoji-json, unpack it, then run
scripts/emoji-data.py path/to/package/data-by-emoji.json"""
import json
import sys

data = json.load(open(sys.argv[1], encoding="utf-8"))
rows = [[e, d["name"]] for e, d in data.items()]
out = "shell/modules/launcher/EmojiData.js"
with open(out, "w", encoding="utf-8") as f:
    f.write(".pragma library\n\n")
    f.write("// Generated by scripts/emoji-data.py from unicode-emoji-json (MIT,\n")
    f.write("// see shell/assets/LICENSE-unicode-emoji-json.txt). [emoji, name]\n")
    f.write("var list = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + "\n")
print(f"{out}: {len(rows)} emoji")
